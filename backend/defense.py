"""Defensive rule generation (purple-team payoff).

A reconstructed attack is only half the value; the other half is *what you'd
deploy in production to catch it next time*. This module turns each proven
stage into a concrete, portable detection/prevention rule, derived from the
observed evidence rather than generic advice:

* **Sigma** rules for the HTTP stages (recon, SQLi, SSTI, upload) — the
  recognized, vendor-neutral detection format;
* **Tetragon** ``TracingPolicy`` for the kernel stages (web-server-spawned
  shells, SUID/privilege escalation, sensitive-file reads, egress). These
  are the same policies BLACKBOX can load to *block* the attack on replay
  (see live-enforcement), so detection and prevention share one artifact.

Pure functions over the reconstruction; YAML is rendered with PyYAML.
"""

from __future__ import annotations

from typing import Any

import yaml

# MITRE tactic -> Sigma tag suffix
_TACTIC_TAG = {
    "reconnaissance": "reconnaissance",
    "initial_access": "initial_access",
    "persistence": "persistence",
    "execution": "execution",
    "privilege_escalation": "privilege_escalation",
    "collection": "collection",
    "command_and_control": "command_and_control",
}

# Shells a web app should never exec (mirror reconstruction/correlation).
SHELL_BINARIES = ["/bin/sh", "/bin/bash", "/bin/dash", "/usr/bin/sh", "/usr/bin/bash"]


def _tactic_key(stage: dict) -> str:
    # stage["tactic"] is a localized dict; map back via the English label.
    en = (stage.get("tactic") or {}).get("en", "").lower().replace(" ", "_")
    return en if en in _TACTIC_TAG else "execution"


def _tags(stage: dict) -> list[str]:
    tags = []
    tactic = _TACTIC_TAG.get(_tactic_key(stage))
    if tactic:
        tags.append(f"attack.{tactic}")
    tags.append(f"attack.{stage['technique_id'].lower()}")
    return tags


def _sigma(stage: dict, *, title: str, product: str, detection: dict,
           level: str) -> dict:
    rule = {
        "title": title,
        "id": f"bb-{stage['key']}",
        "status": "experimental",
        "description": f"Auto-generated by BLACKBOX from a reconstructed "
                       f"{stage['technique_id']} stage.",
        "logsource": {"category": "webserver"} if product == "web"
                     else {"product": "linux"},
        "detection": detection,
        "level": level,
        "tags": _tags(stage),
    }
    return {
        "stage": stage["key"], "technique": stage["technique_id"],
        "format": "sigma", "title": title,
        "yaml": yaml.safe_dump(rule, sort_keys=False, allow_unicode=True),
    }


def _tracingpolicy(stage: dict, *, title: str, spec: dict,
                   enforces: bool, rationale: str) -> dict:
    policy = {
        "apiVersion": "cilium.io/v1alpha1",
        "kind": "TracingPolicy",
        "metadata": {"name": f"bb-{stage['key']}"},
        "spec": spec,
    }
    return {
        "stage": stage["key"], "technique": stage["technique_id"],
        "format": "tetragon", "title": title, "enforces": enforces,
        "rationale": rationale,
        "yaml": yaml.safe_dump(policy, sort_keys=False, allow_unicode=True),
    }


def _exec_block_spec(binaries: list[str], enforce: bool) -> dict:
    """A sched_process_exec TracingPolicy that reports (and optionally kills)
    execution of the given binaries."""
    selector = {"matchBinaries": [{"operator": "In", "values": binaries}]}
    if enforce:
        selector["matchActions"] = [{"action": "Sigkill"}]
    return {
        "tracepoints": [{
            "subsystem": "sched",
            "event": "sched_process_exec",
            "args": [{"index": 4, "type": "string"}],
            "selectors": [selector],
        }]
    }


# per-stage rule builders -------------------------------------------------
def _rules_for_stage(stage: dict) -> list[dict]:
    key = stage["key"]

    if key == "vcs_exposure":
        return [_sigma(stage, title="Version-control path exposed", product="web",
                       level="high", detection={
                           "selection": {"cs-uri|contains": ["/.git/", "/.svn/", "/.hg/"]},
                           "condition": "selection"})]

    if key == "sql_injection":
        return [_sigma(stage, title="SQL injection in request", product="web",
                       level="high", detection={
                           "selection": {"cs-uri|contains": [
                               "union select", "or 1=1", "information_schema",
                               "sleep(", "' or "]},
                           "condition": "selection"})]

    if key == "ssti":
        return [_sigma(stage, title="Server-side template injection", product="web",
                       level="high", detection={
                           "selection": {"cs-uri|contains": [
                               "{{", "__globals__", "__import__", "__class__",
                               "popen(", "os.system"]},
                           "condition": "selection"})]

    if key == "webshell_upload":
        return [_sigma(stage, title="Executable upload to web root", product="web",
                       level="high", detection={
                           "selection": {"cs-method": "POST", "cs-uri|contains": "upload"},
                           "ext": {"cs-uri|endswith": [".phtml", ".php", ".jsp", ".asp"]},
                           "condition": "selection and ext"})]

    if key == "webshell_rce":
        return [
            _tracingpolicy(stage, title="Block web-server-spawned shells",
                           enforces=True,
                           rationale="A web application executing /bin/sh is "
                                     "the signature of RCE; kill it at exec.",
                           spec=_exec_block_spec(SHELL_BINARIES, enforce=True)),
            _sigma(stage, title="Shell spawned by web server", product="linux",
                   level="high", detection={
                       "selection": {"ParentImage|endswith": [
                           "apache2", "nginx", "uvicorn", "node", "php-fpm"],
                           "Image|endswith": ["/sh", "/bash", "/dash"]},
                       "condition": "selection"})]

    if key == "privilege_escalation":
        return [
            _tracingpolicy(stage, title="Block SUID/privileged shells",
                           enforces=True,
                           rationale="Kill execution of planted SUID shells "
                                     "(rootbash) and privilege-preserving shells.",
                           spec=_exec_block_spec(
                               ["/var/tmp/rootbash", "/tmp/rootbash"], enforce=True)),
            _sigma(stage, title="SUID shell / privilege escalation", product="linux",
                   level="critical", detection={
                       "selection": {"CommandLine|contains": [
                           "rootbash", " -p", "chmod +s", "chmod 4755",
                           "export PATH=/tmp"]},
                       "condition": "selection"})]

    if key == "sensitive_access":
        return [
            _tracingpolicy(stage, title="Watch reads of protected files",
                           enforces=False,
                           rationale="Alert on any process opening /root or "
                                     "/etc/shadow — secrets being reached.",
                           spec={"kprobes": [{
                               "call": "security_file_open", "syscall": False,
                               "args": [{"index": 0, "type": "file"}],
                               "selectors": [{"matchArgs": [{
                                   "index": 0, "operator": "Prefix",
                                   "values": ["/root/", "/etc/shadow"]}]}]}]}),
            _sigma(stage, title="Sensitive file read", product="linux",
                   level="high", detection={
                       "selection": {"CommandLine|contains": ["/root/", "/etc/shadow"]},
                       "condition": "selection"})]

    if key == "outbound_connection":
        return [_sigma(stage, title="Outbound connection from service", product="linux",
                       level="medium", detection={
                           "selection": {"Initiated": "true"},
                           "condition": "selection"})]

    return []


def generate_rules(recon: dict) -> dict[str, Any]:
    """Generate defensive rules for every reconstructed stage."""
    rules: list[dict] = []
    for stage in recon.get("stages", []):
        rules.extend(_rules_for_stage(stage))
    return {
        "rules": rules,
        "rule_count": len(rules),
        "sigma_count": sum(1 for r in rules if r["format"] == "sigma"),
        "tetragon_count": sum(1 for r in rules if r["format"] == "tetragon"),
        "enforceable": sorted({
            r["stage"] for r in rules
            if r["format"] == "tetragon" and r.get("enforces")}),
    }
